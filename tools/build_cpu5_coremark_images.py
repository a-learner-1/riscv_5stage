"""Build CPU5 CoreMark RV32IM images for the schema4/profile2 system port.

Each case is one frozen (D0 backend x I/D cache) configuration of the CPU5
CoreMark platform. The generated header is the only place where the firmware
learns which hardware it belongs to; the port header rejects anything that is
not the CPU5 schema4 identity.
"""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "build/cpu5_s18_coremark/firmware"
ROM_WORDS, RAM_WORDS, MIN_STACK_BYTES = 8192, 4096, 2048
CLOCK_HZ, UART_BAUD, ITERATIONS = 50000000, 5000000, 1
CACHE_SETS, CACHE_LINE_WORDS = 4, 4
BTB_ENTRIES, BP_ENABLE = 16, 1
CACHE_GEOMETRY = (2 << 24) | (CACHE_SETS << 16) | (CACHE_LINE_WORDS * 4)
BP_CONFIG = (BTB_ENTRIES << 16) | BP_ENABLE
STATS_SCHEMA, PROFILE_SCHEMA, PROFILE_FIELDS, PROFILE_BITS, WINDOW_BYTES = 4, 2, 10, 64, 0x200
EXPECTED_CRCS = {"seed": 0xE9F5, "list": 0xE714, "matrix": 0x1FD7, "state": 0x8E3A}
MEM_LOCATION = ("Static; ROM 32 KiB @0x00000000; RAM 16 KiB @0x00010000; CPU5; "
                "schema4 ten-class statistics @0x30000000; core:memory clock=1:1")
CASES = (
    {"case": 0, "d0": 0, "cache": 0},
    {"case": 1, "d0": 0, "cache": 3},
    {"case": 2, "d0": 1, "cache": 0},
    {"case": 3, "d0": 1, "cache": 3},
)
DEFAULT_CROSS = r"D:\Tools\xpack-riscv-none-elf-gcc-15.2.0-1-win32-x64\xpack-riscv-none-elf-gcc-15.2.0-1\bin\riscv-none-elf-"
COMPILE_SOURCES = ["software/cpu5_coremark/start.S",
                   "software/cpu5_coremark/core_portme_cpu5.c"] + [
    "benchmarks/coremark/" + name for name in
    ("core_list_join.c", "core_main.c", "core_matrix.c", "core_state.c", "core_util.c")]
REQUIRED_SYMBOLS = ("_start", "main", "tohost", "__bss_start", "__bss_end", "__stack_top")
OBSERVATION_SYMBOLS = ("coremark_failed", "coremark_actual_iterations", "coremark_elapsed_ticks")


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def source_hashes():
    sources = set(COMPILE_SOURCES)
    for directory in (ROOT / "benchmarks/coremark", ROOT / "software/coremark_port",
                      ROOT / "software/cpu5_coremark"):
        sources.update(path.relative_to(ROOT).as_posix()
                       for path in directory.glob("*.h"))
    sources.update(("software/cpu5_coremark/link.ld", "software/mmio.h",
                    "software/timer.h", "software/coremark_port/core_portme.c",
                    "tools/build_cpu5_coremark_images.py"))
    return {name: sha(ROOT / name) for name in sorted(sources)}


def case_config(case):
    return {
        "CPU5_COREMARK_PLATFORM_NAME": '"cpu5"',
        "CPU5_COREMARK_CACHE_ENABLE": case["cache"],
        "CPU5_COREMARK_D0_BRAM": case["d0"],
        "CPU5_COREMARK_BACKEND_ID": case["d0"],
        "CPU5_COREMARK_BP_ENABLE": BP_ENABLE,
        "CPU5_COREMARK_BTB_ENTRIES": BTB_ENTRIES,
        "CPU5_COREMARK_BP_CONFIG": BP_CONFIG,
        "CPU5_COREMARK_CACHE_GEOMETRY": CACHE_GEOMETRY,
        "CPU5_COREMARK_CACHE_SETS": CACHE_SETS,
        "CPU5_COREMARK_CACHE_LINE_WORDS": CACHE_LINE_WORDS,
        "CPU5_COREMARK_STATS_SCHEMA": STATS_SCHEMA,
        "CPU5_COREMARK_PROFILE_SCHEMA": PROFILE_SCHEMA,
        "CPU5_COREMARK_PROFILE_FIELDS": PROFILE_FIELDS,
        "CPU5_COREMARK_PROFILE_BITS": PROFILE_BITS,
        "CPU5_COREMARK_WINDOW_BYTES": WINDOW_BYTES,
        "CPU5_COREMARK_ENABLE_M": 1,
        "COREMARK_CLOCK_HZ": CLOCK_HZ,
        "COREMARK_UART_BAUD": UART_BAUD,
        "COREMARK_FORMAL": 0,
        "ITERATIONS": ITERATIONS,
        "PERFORMANCE_RUN": 1,
        "VALIDATION_RUN": 0,
        "COREMARK_PROFILE_NAME": '"cpu5-smoke"',
        "COREMARK_BUILD_ITERATIONS": ITERATIONS,
        "MEM_LOCATION": json.dumps(MEM_LOCATION),
    }


def write_config(directory, config, version, flags):
    lines = ["/* Generated by tools/build_cpu5_coremark_images.py; do not edit. */",
             "#ifndef COREMARK_BUILD_CONFIG_H", "#define COREMARK_BUILD_CONFIG_H"]
    for name, value in config.items():
        lines.append(f"#define {name} {value}")
    lines.append("#define COMPILER_VERSION " + json.dumps(version))
    lines.append("#define COMPILER_FLAGS " + json.dumps(" ".join(flags + ["-lgcc"])))
    lines.append("#endif")
    (directory / "coremark_build_config.h").write_text("\n".join(lines) + "\n",
                                                       encoding="ascii")


def validate_text(text):
    """Reject any linked word that is not RV32IM, including libgcc code."""
    if len(text) % 4:
        raise RuntimeError("CPU5 CoreMark .text is not a multiple of four bytes")
    allowed = {0x03, 0x0F, 0x13, 0x17, 0x23, 0x33, 0x37, 0x63, 0x67, 0x6F, 0x73}
    for address in range(0, len(text), 4):
        word = int.from_bytes(text[address:address + 4], "little")
        opcode, funct3, funct7 = word & 0x7F, (word >> 12) & 7, word >> 25
        valid = word & 3 == 3 and opcode in allowed
        if opcode == 0x33:
            valid &= funct7 == 0 or (funct7 == 0x20 and funct3 in (0, 5)) or funct7 == 1
        if opcode == 0x13 and funct3 in (1, 5):
            valid &= funct7 == 0 or (funct3 == 5 and funct7 == 0x20)
        if opcode == 0x03:
            valid &= funct3 in (0, 1, 2, 4, 5)
        if opcode == 0x23:
            valid &= funct3 in (0, 1, 2)
        if opcode == 0x63:
            valid &= funct3 in (0, 1, 4, 5, 6, 7)
        if opcode == 0x67:
            valid &= funct3 == 0
        # Base RV32I ECALL/EBREAK only: CPU5 CoreMark never traps by design.
        if opcode == 0x73:
            valid &= word in (0x00000073, 0x00100073)
        if opcode == 0x0F:
            valid &= funct3 == 0
        if not valid:
            raise RuntimeError(f"Non-RV32IM instruction 0x{word:08x} at 0x{address:08x}")


def image(payload, target, words, fill):
    if len(payload) > words * 4:
        raise RuntimeError("Image overflow: " + str(target))
    padded = payload + b"\0" * (-len(payload) % 4)
    data = [int.from_bytes(padded[index:index + 4], "little")
            for index in range(0, len(padded), 4)]
    data += [fill] * (words - len(data))
    target.write_text("".join(f"{word:08x}\n" for word in data), encoding="ascii")


def toolchain_identity(cross):
    probes = []

    def query(arguments):
        command = [cross + "gcc", *arguments]
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True,
                                encoding="utf-8", errors="replace")
        if result.returncode or re.search(r"warning:|error:", result.stdout + result.stderr, re.I):
            raise RuntimeError("CPU5 compiler probe failed: " + " ".join(command))
        probes.append(dict(command=command, exit_code=result.returncode,
                           stdout=result.stdout, stderr=result.stderr))
        return result.stdout.strip()

    def executable(name):
        for path in (Path(name), Path(name + ".exe")):
            if path.is_file():
                return path.resolve()
        found = shutil.which(name)
        if not found:
            raise RuntimeError("CPU5 compiler tool missing: " + name)
        return Path(found).resolve()

    version = query(["--version"])
    options = ["-march=rv32im", "-mabi=ilp32"]
    selected = query([*options, "-print-multi-directory"])
    available = query(["-print-multi-lib"])
    entry = next((line for line in available.splitlines()
                  if line.split(";", 1)[0] == selected), "")
    switches = set(entry.split(";", 1)[1].split("@")) if ";" in entry else set()
    if switches != {"", "march=rv32im", "mabi=ilp32"}:
        raise RuntimeError("CPU5 CoreMark requires the explicit rv32im/ilp32 multilib")
    libgcc = Path(query([*options, "-print-libgcc-file-name"])).resolve()
    if not libgcc.is_file():
        raise RuntimeError("CPU5 selected libgcc is missing")
    tools = {name: executable(cross + name)
             for name in ("gcc", "objcopy", "objdump", "nm", "size")}
    for name in ("cc1", "as", "ld"):
        tools[name] = executable(query(["-print-prog-name=" + name]))
    return dict(compiler_version_full=version, multilib_selected=selected,
                multilib_entry=entry, multilib_available=available,
                libgcc_path=str(libgcc), libgcc_sha256=sha(libgcc),
                tools={name: dict(path=str(path), sha256=sha(path))
                       for name, path in tools.items()}, probes=probes)


def build_case(case, cross):
    inputs = source_hashes()
    directory = OUT / f"case{case['case']}"
    directory.mkdir(parents=True, exist_ok=True)
    config = case_config(case)
    flags = ["-march=rv32im", "-mabi=ilp32", "-O2", "-ffreestanding", "-fno-builtin",
             "-fno-stack-protector", "-fno-pic", "-msmall-data-limit=0", "-mno-relax",
             "-ffunction-sections", "-fdata-sections", "-Wall", "-Wextra",
             "-Wno-maybe-uninitialized", f"-DITERATIONS={ITERATIONS}",
             "-DPERFORMANCE_RUN=1", "-DTOTAL_DATA_SIZE=2000",
             "-I" + directory.relative_to(ROOT).as_posix(),
             "-Isoftware/cpu5_coremark", "-Isoftware/coremark_port",
             "-Ibenchmarks/coremark", "-Isoftware"]
    steps = []
    toolchain = toolchain_identity(cross)
    version = toolchain["compiler_version_full"].splitlines()[0]
    write_config(directory, config, version, flags)
    elf = directory / "program.elf"
    link = ["-nostdlib", "-nostartfiles", "-static",
            "-Wl,-T,software/cpu5_coremark/link.ld", "-Wl,--gc-sections",
            "-Wl,--no-relax", "-Wl,-Map," + (directory / "program.map").relative_to(ROOT).as_posix()]
    commands = [
        [cross + "gcc", *flags, *link, *COMPILE_SOURCES, "-lgcc", "-o", str(elf.relative_to(ROOT))],
        [cross + "objcopy", "-O", "binary", "-j", ".text", str(elf.relative_to(ROOT)),
         (directory / "program_text.bin").relative_to(ROOT).as_posix()],
        [cross + "objcopy", "-O", "binary", "-j", ".data", str(elf.relative_to(ROOT)),
         (directory / "program_data.bin").relative_to(ROOT).as_posix()],
        [cross + "objdump", "-d", "-S", str(elf.relative_to(ROOT))],
        [cross + "nm", "-n", str(elf.relative_to(ROOT))],
        [cross + "size", str(elf.relative_to(ROOT))],
    ]
    outputs = {}
    for index, command in enumerate(commands):
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True,
                                encoding="utf-8", errors="replace")
        (directory / f"command{index}_stdout.log").write_text(result.stdout, encoding="utf-8")
        (directory / f"command{index}_stderr.log").write_text(result.stderr, encoding="utf-8")
        combined = result.stdout + result.stderr
        if result.returncode:
            raise RuntimeError(f"case{case['case']} command{index} failed: " + combined[-4000:])
        if re.search(r"warning:|error:", combined, re.I):
            raise RuntimeError(f"case{case['case']} command{index} diagnostics: " + combined[-4000:])
        steps.append(dict(command=command, exit_code=result.returncode))
        outputs[index] = result.stdout
    (directory / "program.lst").write_text(outputs[3], encoding="utf-8")
    symbols = {}
    for line in outputs[4].splitlines():
        fields = line.split()
        if len(fields) == 3 and re.fullmatch(r"[0-9a-fA-F]+", fields[0]):
            symbols[fields[2]] = int(fields[0], 16)
    for name in REQUIRED_SYMBOLS:
        if name not in symbols:
            raise RuntimeError(f"case{case['case']} missing symbol {name}")
    if symbols["_start"] != 0 or symbols["tohost"] != 0x13FFC:
        raise RuntimeError(f"case{case['case']} unexpected _start/tohost address")
    headroom = symbols["__stack_top"] - symbols["__bss_end"]
    if headroom < MIN_STACK_BYTES:
        raise RuntimeError(f"case{case['case']} only {headroom} bytes of stack headroom")
    text = (directory / "program_text.bin").read_bytes()
    data = (directory / "program_data.bin").read_bytes()
    if len(text) > ROM_WORDS * 4 or len(data) > RAM_WORDS * 4:
        raise RuntimeError(f"case{case['case']} image exceeds physical ROM/RAM")
    validate_text(text)
    image(text, directory / "program.hex", ROM_WORDS, 0x13)
    image(data, directory / "program_data.hex", RAM_WORDS, 0)
    for name in OBSERVATION_SYMBOLS:
        if name in symbols and not 0x10000 <= symbols[name] < 0x13FFC:
            raise RuntimeError(f"case{case['case']} observation symbol outside RAM: {name}")
    record = {
        "case": case["case"], "d0": case["d0"], "cache": case["cache"],
        "config": {name: str(value) for name, value in config.items()},
        "clock_hz": CLOCK_HZ, "uart_baud": UART_BAUD, "iterations": ITERATIONS,
        "formal": 0, "seed_profile": "performance", "total_data_size": 2000,
        "compiler": version, "compiler_flags": flags, "linker_flags": link,
        "cascade_geometry": f"0x{CACHE_GEOMETRY:08x}", "bp_config": f"0x{BP_CONFIG:08x}",
        "text_bytes": len(text), "data_bytes": len(data),
        "bss_bytes": symbols["__bss_end"] - symbols["__bss_start"],
        "stack_headroom_bytes": headroom, "minimum_stack_headroom_bytes": MIN_STACK_BYTES,
        "size_output": outputs[5].strip(),
        "text_sha256": sha(directory / "program_text.bin"),
        "data_sha256": sha(directory / "program_data.bin"),
        "elf_sha256": sha(elf),
        "images_sha256": {name: sha(directory / name)
                          for name in ("program.hex", "program_data.hex")},
        "symbols": {name: f"0x{address:08x}" for name, address in sorted(symbols.items())},
        "expected_crc": {name: f"0x{value:04x}" for name, value in EXPECTED_CRCS.items()},
        "steps": steps, "compiler_generated_warnings": 0,
        "sources_sha256": inputs,
        "toolchain": toolchain,
        "hardware_download_performed": False, "formal_score_measured": False,
    }
    if inputs != source_hashes():
        raise RuntimeError(f"case{case['case']} build inputs changed during compilation")
    artifacts = ["coremark_build_config.h", "program.elf", "program_text.bin",
                 "program_data.bin", "program.hex", "program_data.hex",
                 "program.lst", "program.map"] + [
        f"command{index}_{stream}.log" for index in range(len(commands))
        for stream in ("stdout", "stderr")]
    # build.json is authenticated by the runner's outer raw receipt. It must
    # never hash its own previous version when this output folder is reused.
    record["artifact_sha256"] = {
        (directory / name).relative_to(ROOT).as_posix(): sha(directory / name)
        for name in artifacts}
    record["generated_config_sha256"] = sha(directory / "coremark_build_config.h")
    (directory / "build.json").write_text(json.dumps(record, indent=2) + "\n",
                                          encoding="utf-8")
    return record


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cross", default=DEFAULT_CROSS)
    parser.add_argument("--generate-only", action="store_true")
    arguments = parser.parse_args()
    OUT.mkdir(parents=True, exist_ok=True)
    before = source_hashes()
    records = [build_case(case, arguments.cross) for case in CASES]
    assert before == source_hashes(), "CPU5 CoreMark sources changed during the build"
    summary = dict(status="FIRMWARE BUILT", cases=len(records),
                   compiler=records[0]["compiler"],
                   text_bytes=[record["text_bytes"] for record in records],
                   data_bytes=[record["data_bytes"] for record in records],
                   stack_headroom=[record["stack_headroom_bytes"] for record in records])
    (OUT / "firmware_manifest.json").write_text(json.dumps(summary, indent=2) + "\n",
                                               encoding="utf-8")
    print(json.dumps(summary))


if __name__ == "__main__":
    try:
        main()
    except (OSError, RuntimeError, subprocess.CalledProcessError) as error:
        print("ERROR: " + str(error), file=sys.stderr)
        sys.exit(1)
