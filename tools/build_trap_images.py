"""Build the opt-in RV32I/Zicsr synchronous exception C demonstration."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
BUILD = ROOT / "build" / "trap_firmware"
FALLBACK = Path("D:/Tools/xpack-riscv-none-elf-gcc-15.2.0-1-win32-x64/"
                "xpack-riscv-none-elf-gcc-15.2.0-1/bin/riscv-none-elf-")


def prefix():
    configured = os.environ.get("TRAP_CROSS") or os.environ.get("BOARD_CROSS")
    if configured:
        return configured
    compiler = shutil.which("riscv-none-elf-gcc")
    if compiler:
        return compiler.rsplit("gcc", 1)[0]
    if Path(str(FALLBACK) + "gcc.exe").is_file():
        return str(FALLBACK)
    raise RuntimeError("RISC-V GCC missing: set TRAP_CROSS")


def rel(path):
    return Path(path).relative_to(ROOT).as_posix()


def run(args, log, save=None):
    command = [str(v) for v in args]
    log.write("$ " + subprocess.list2cmdline(command) + "\n")
    result = subprocess.run(command, cwd=ROOT, stdout=subprocess.PIPE,
                            stderr=subprocess.STDOUT, text=True,
                            encoding="utf-8", errors="replace")
    log.write(result.stdout)
    log.flush()
    if save:
        save.write_text(result.stdout, encoding="utf-8")
    if result.returncode:
        raise RuntimeError("Build failed; see " + str(BUILD / "build.log"))
    return result.stdout


def image(payload, target, words, fill):
    if len(payload) > words * 4:
        raise RuntimeError("Image overflow: " + str(target))
    payload += b"\0" * (-len(payload) % 4)
    data = [int.from_bytes(payload[i:i + 4], "little")
            for i in range(0, len(payload), 4)]
    data += [fill] * (words - len(data))
    target.write_text("".join(f"{v:08x}\n" for v in data), encoding="ascii")


def main():
    argparse.ArgumentParser(description=__doc__).parse_args()
    BUILD.mkdir(parents=True, exist_ok=True)
    tool = prefix()
    elf = BUILD / "trap_demo.elf"
    with (BUILD / "build.log").open("w", encoding="utf-8") as log:
        run([tool + "gcc", "--version"], log)
        flags = ["-march=rv32i_zicsr", "-mabi=ilp32", "-O2", "-ffreestanding",
                 "-fno-builtin", "-fno-stack-protector", "-fno-pic",
                 "-msmall-data-limit=0", "-mno-relax", "-Wall", "-Wextra", "-Werror",
                 "-nostdlib", "-nostartfiles", "-static", "-Wl,-T,software/link.ld",
                 "-Wl,--no-relax", "-Wl,-Map," + rel(BUILD / "trap_demo.map")]
        run([tool + "gcc", *flags, "software/start.S", "software/trap_entry.S",
             "software/trap_demo.c", "-lgcc", "-o", rel(elf)], log)
        binaries = {}
        for section in ("text", "data"):
            binary = BUILD / ("trap_demo_" + section + ".bin")
            run([tool + "objcopy", "-O", "binary", "-j", "." + section,
                 rel(elf), rel(binary)], log)
            binaries[section] = binary.read_bytes()
        run([tool + "objdump", "-d", "-S", rel(elf)], log, BUILD / "trap_demo.dump")
        output = run([tool + "nm", "-n", rel(elf)], log, BUILD / "trap_demo.symbols")
        symbols = {}
        for line in output.splitlines():
            fields = line.split()
            if len(fields) == 3:
                symbols[fields[2]] = int(fields[0], 16)
    for name in ("trap_entry", "trap_demo_ecall", "trap_demo_ebreak",
                 "trap_demo_illegal", "trap_demo_badcsr", "trap_demo_count",
                 "trap_demo_log", "trap_demo_guard", "trap_demo_resumed"):
        if name not in symbols:
            raise RuntimeError("Missing expected symbol: " + name)
    if symbols["trap_entry"] & 3 or symbols["__bss_end"] > symbols["__stack_top"] - 128:
        raise RuntimeError("Trap alignment/stack safety check failed")
    image(binaries["text"], ROOT / "programs/trap_demo.hex", 8192, 0x13)
    image(binaries["data"], ROOT / "programs/trap_demo_data.hex", 4096, 0)
    # Address macros are generated from the ELF; the TB never assumes C layout.
    lines = ["// Generated by tools/build_trap_images.py; do not edit.\n"]
    for name in ("trap_entry", "trap_demo_ecall", "trap_demo_ebreak",
                 "trap_demo_illegal", "trap_demo_badcsr", "trap_demo_count",
                 "trap_demo_log", "trap_demo_guard", "trap_demo_resumed"):
        lines.append(f"`define {name.upper()} 32'h{symbols[name]:08x}\n")
    (ROOT / "programs/trap_demo_symbols.vh").write_text("".join(lines), encoding="ascii")
    hashes = {name: hashlib.sha256((ROOT / "programs" / name).read_bytes()).hexdigest()
              for name in ("trap_demo.hex", "trap_demo_data.hex", "trap_demo_symbols.vh")}
    report = {"march": "rv32i_zicsr", "text_bytes": len(binaries["text"]),
              "data_bytes": len(binaries["data"]), "symbols": symbols,
              "sha256": hashes, "requires_ENABLE_TRAPS": 1}
    (BUILD / "build_report.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
    print("Trap demo built:", len(binaries["text"]), "text bytes,",
          len(binaries["data"]), "data bytes; ENABLE_TRAPS=1 required")


if __name__ == "__main__":
    main()
